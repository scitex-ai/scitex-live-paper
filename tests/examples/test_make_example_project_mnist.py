"""Pins for the ``example-project-mnist`` seed bundle (operator orders).

The bundle itself is generated by
``examples/make_example_project_mnist.py`` (needs scikit-learn +
network, so generation is NOT part of the suite). These tests pin the
COMMITTED artifact: it loads, carries three computed claims with
page-3 anchors over the accuracy figure, and ships provenance good
enough to regenerate.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import pytest
from pathlib import Path

from scitex_live_paper import bundle as bundle_module

EXAMPLES = Path(__file__).resolve().parents[2] / "examples"
BUNDLE = EXAMPLES / "example-project-mnist"
GENERATOR = EXAMPLES / "make_example_project_mnist.py"


def _clean_subprocess_env() -> dict[str, str]:
    """Subprocess env without ambient ``PYTHONPATH`` shadowing.

    Host harnesses (CI containers, agent runtimes) may inject their
    own ``PYTHONPATH``; the generator must import the *project*
    interpreter's own site-packages (matplotlib/PIL ABI), so the
    inherited entry is dropped for the child.
    """
    return {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}


EXPECTED_CLAIM_IDS = {
    "mnist_logreg_accuracy",
    "mnist_knn_accuracy",
    "mnist_model_comparison",
}


def test_generator_help_lists_quick_mode():
    # Arrange
    command = [sys.executable, str(GENERATOR), "--help"]
    # Act
    completed = subprocess.run(
        command, capture_output=True, text=True, timeout=60, env=_clean_subprocess_env()
    )
    # Assert
    assert completed.returncode == 0 and "--quick" in completed.stdout, completed.stderr


def test_mnist_bundle_loads_three_claims():
    # Arrange
    # Act
    loaded = bundle_module.load(BUNDLE)
    # Assert
    assert {c.claim_id for c in loaded.claims} == EXPECTED_CLAIM_IDS and len(
        loaded.claims
    ) == 3


def test_mnist_claims_carry_computed_accuracies():
    # Arrange
    # Act
    payload = json.loads((BUNDLE / "claims.json").read_text(encoding="utf-8"))
    values = {c["claim_id"]: c["claim_value"] for c in payload["claims"]}
    lr = float(values["mnist_logreg_accuracy"].rsplit("=", 1)[1])
    knn = float(values["mnist_knn_accuracy"].rsplit("=", 1)[1])
    diff = float(values["mnist_model_comparison"].rsplit("=", 1)[1].split()[0])
    # Assert
    assert (
        payload["schema"] == "scitex-clew.claims/v1"
        and 0.5 < lr <= 1.0
        and 0.5 < knn <= 1.0
        and abs(diff - (lr - knn)) < 2e-4
    )


@pytest.mark.parametrize("claim_id", ["mnist_logreg_accuracy", "mnist_knn_accuracy"])
def test_mnist_accuracy_claim_uses_decimal(claim_id):
    # Arrange
    # Act
    payload = json.loads((BUNDLE / "claims.json").read_text())
    value = next(
        c["claim_value"] for c in payload["claims"] if c["claim_id"] == claim_id
    )
    # Assert
    assert re.search(r"= 0\.\d{4}$", value)


@pytest.mark.parametrize("claim_id", ["mnist_logreg_accuracy", "mnist_knn_accuracy"])
def test_mnist_accuracy_anchors_page_three(claim_id):
    # Arrange
    # Act
    payload = json.loads((BUNDLE / "claims.json").read_text())
    anchor = next(c["anchor"] for c in payload["claims"] if c["claim_id"] == claim_id)
    x0, y0, x1, y1 = anchor["bbox"]
    # Assert
    assert anchor["page"] == 3 and 0 <= x0 < x1 <= 612.0 and 0 <= y0 < y1 <= 792.0


@pytest.mark.parametrize(
    "relative,minimum_size",
    [
        ("manuscript.pdf", 10000),
        ("figz/mnist_accuracy.png", 1),
        ("figz/mnist_digits.png", 1),
    ],
)
def test_mnist_bundle_ships_visual_assets(relative, minimum_size):
    # Arrange
    # Act
    size = (BUNDLE / relative).stat().st_size
    # Assert
    assert size > minimum_size


@pytest.mark.parametrize("claim_id", sorted(EXPECTED_CLAIM_IDS))
def test_mnist_dag_references_every_claim(claim_id):
    # Arrange
    # Act
    dag = (BUNDLE / "dag.mmd").read_text()
    # Assert
    assert claim_id in dag


@pytest.mark.parametrize("marker", ["mnist_784", "seed", "results"])
def test_mnist_provenance_records_reproduction_inputs(marker):
    # Arrange
    # Act
    provenance = (BUNDLE / "provenance.yaml").read_text()
    # Assert
    assert marker in provenance
