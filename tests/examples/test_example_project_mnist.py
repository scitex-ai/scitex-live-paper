"""Pins for the ``example-project-mnist`` seed bundle (operator orders).

The bundle itself is generated by
``examples/make_example_project_mnist.py`` (needs scikit-learn +
network, so generation is NOT part of the suite). These tests pin the
COMMITTED artifact: it loads, carries three computed claims with
page-3 anchors over the accuracy figure, and ships provenance good
enough to regenerate.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from scitex_live_paper import bundle as bundle_module

EXAMPLES = Path(__file__).resolve().parents[2] / "examples"
BUNDLE = EXAMPLES / "example-project-mnist"
GENERATOR = EXAMPLES / "make_example_project_mnist.py"

EXPECTED_CLAIM_IDS = {
    "mnist_logreg_accuracy",
    "mnist_knn_accuracy",
    "mnist_model_comparison",
}


def test_generator_help_lists_quick_mode():
    completed = subprocess.run(
        [sys.executable, str(GENERATOR), "--help"],
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert completed.returncode == 0
    assert "--quick" in completed.stdout


def test_mnist_bundle_loads_with_three_claims():
    loaded = bundle_module.load(BUNDLE)
    assert len(loaded.claims) == 3
    assert {c.claim_id for c in loaded.claims} == EXPECTED_CLAIM_IDS


def test_mnist_claims_carry_computed_accuracies():
    payload = json.loads((BUNDLE / "claims.json").read_text(encoding="utf-8"))
    assert payload["schema"] == "scitex-clew.claims/v1"
    values = {c["claim_id"]: c["claim_value"] for c in payload["claims"]}
    assert re.search(r"= 0\.\d{4}$", values["mnist_logreg_accuracy"])
    assert re.search(r"= 0\.\d{4}$", values["mnist_knn_accuracy"])
    lr = float(values["mnist_logreg_accuracy"].rsplit("=", 1)[1])
    knn = float(values["mnist_knn_accuracy"].rsplit("=", 1)[1])
    assert 0.5 < lr <= 1.0 and 0.5 < knn <= 1.0  # both real, computed
    diff = float(values["mnist_model_comparison"].rsplit("=", 1)[1].split()[0])
    assert abs(diff - (lr - knn)) < 2e-4  # comparison matches the pair


def test_mnist_accuracy_claims_anchor_page_three_figure():
    payload = json.loads((BUNDLE / "claims.json").read_text(encoding="utf-8"))
    by_id = {c["claim_id"]: c for c in payload["claims"]}
    for cid in ("mnist_logreg_accuracy", "mnist_knn_accuracy"):
        anchor = by_id[cid]["anchor"]
        assert anchor["page"] == 3
        x0, y0, x1, y1 = anchor["bbox"]
        assert 0 <= x0 < x1 <= 612.0 and 0 <= y0 < y1 <= 792.0


def test_mnist_bundle_ships_manuscript_figures_and_provenance():
    assert (BUNDLE / "manuscript.pdf").stat().st_size > 10_000
    assert (BUNDLE / "figz" / "mnist_accuracy.png").is_file()
    assert (BUNDLE / "figz" / "mnist_digits.png").is_file()
    dag = (BUNDLE / "dag.mmd").read_text(encoding="utf-8")
    for cid in EXPECTED_CLAIM_IDS:
        assert cid in dag
    prov = (BUNDLE / "provenance.yaml").read_text(encoding="utf-8")
    assert "mnist_784" in prov and "seed" in prov and "results" in prov
